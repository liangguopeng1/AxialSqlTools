def make_entries(d):
    lines = []
    for k, v in d.items():
        v = v.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        lines.append(f'  <data name="{k}" xml:space="preserve"><value>{v}</value></data>')
    return '\n'.join(lines)

def append_keys(filename, entries):
    path = os.path.join(BASE, filename)
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()
    if 'QuickSearch_HeaderTitle' in content:
        print(f'skip {filename} (already appended)')
        return
    content = content.replace('</root>', make_entries(entries) + '\n</root>')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(content)
    print(f'updated {filename}')

